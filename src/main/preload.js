const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (cb) => {
  const h = (_e, data) => cb(data);
  ipcRenderer.on(channel, h);
  return () => ipcRenderer.removeListener(channel, h);
};

contextBridge.exposeInMainWorld('api', {
  init: () => ipcRenderer.invoke('lib:init'),
  addFolder: () => ipcRenderer.invoke('lib:addFolder'),
  addFiles: () => ipcRenderer.invoke('lib:addFiles'),
  removeFolder: (f) => ipcRenderer.invoke('lib:removeFolder', f),
  addPaths: (paths) => ipcRenderer.invoke('lib:addPaths', paths),
  rescan: () => ipcRenderer.invoke('lib:rescan'),
  store: (key, value) => ipcRenderer.send('store:set', key, value),
  setSettings: (patch) => ipcRenderer.send('settings:set', patch),
  lyrics: (t) => ipcRenderer.invoke('lyrics:get', t),
  lyricsSearch: (q) => ipcRenderer.invoke('lyrics:search', q),
  lyricsGenius: (url) => ipcRenderer.invoke('lyrics:genius', url),
  lyricsSet: (id, data) => ipcRenderer.invoke('lyrics:set', id, data),
  coverSearch: (q) => ipcRenderer.invoke('cover:search', q),
  artistSearch: (q) => ipcRenderer.invoke('artist:search', q),
  artistApply: (key, url) => ipcRenderer.invoke('artist:apply', key, url),
  artistFile: (key) => ipcRenderer.invoke('artist:file', key),
  artistReset: (key, auto) => ipcRenderer.invoke('artist:reset', key, auto),
  onArtists: on('lib:artists'),
  coverApply: (ids, url) => ipcRenderer.invoke('cover:apply', ids, url),
  coverFile: (ids) => ipcRenderer.invoke('cover:file', ids),
  coverReset: (ids, auto) => ipcRenderer.invoke('cover:reset', ids, auto),
  radioSearch: (q) => ipcRenderer.invoke('radio:search', q),
  radioClick: (id) => ipcRenderer.send('radio:click', id),
  iaSearch: (q) => ipcRenderer.invoke('ia:search', q),
  scStatus: () => ipcRenderer.invoke('sc:status'),
  scSetKeys: (id, secret) => ipcRenderer.invoke('sc:setKeys', id, secret),
  scClearKeys: () => ipcRenderer.invoke('sc:clearKeys'),
  scSearch: (q, next) => ipcRenderer.invoke('sc:search', q, next),
  scResolve: (link) => ipcRenderer.invoke('sc:resolve', link),
  scStream: (id) => ipcRenderer.invoke('sc:stream', id),
  scFavs: (list) => ipcRenderer.invoke('sc:favs', list),
  iaItem: (id) => ipcRenderer.invoke('ia:item', id),
  iaDownload: (list) => ipcRenderer.invoke('ia:download', list),
  onIaProgress: on('ia:progress'),
  showItem: (p) => ipcRenderer.send('shell:showItem', p),
  openPath: (p) => ipcRenderer.send('shell:openPath', p),
  openExternal: (u) => ipcRenderer.send('shell:openExternal', u),
  clearCache: () => ipcRenderer.invoke('cache:clear'),
  sendState: (st) => ipcRenderer.send('player:state', st),
  command: (cmd, arg) => ipcRenderer.send('player:command', { cmd, arg }),
  mini: (on) => ipcRenderer.send('win:mini', on),
  quit: () => ipcRenderer.send('app:quit'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  updateGet: () => ipcRenderer.invoke('update:get'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.send('update:install'),
  onUpdate: on('update'),
  onTracks: on('lib:tracks'),
  onProgress: on('lib:progress'),
  onCommand: on('player:command'),
  onState: on('player:state'),
  onSettings: on('settings'),
  onOpenFiles: on('open-files'),
});
